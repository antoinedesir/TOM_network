  function renderPapers(opts) {
    var filters = document.getElementById(opts.filters);
    var body = document.getElementById(opts.body);
    if (!body || !window.PAPERS) {
      if (body) body.innerHTML = "<p>Publication data not loaded — run <strong>python build.py</strong> in tom_network.</p>";
      return;
    }
    var P = papers();
    var names = window.PAPERS.faculty;
    var state = { f: -1, y: "", q: "" };

    function surname(n) {
      var t = n.replace(/^D\. /, "").split(" ");
      return t.length > 2 && /^(Van|van|de|De)$/.test(t[1]) ? t.slice(1).join(" ") : t[t.length - 1];
    }
    var order = names.map(function (n, i) { return i; })
      .sort(function (a, b) { return surname(names[a]).localeCompare(surname(names[b])); });
    var years = P.map(function (p) { return p.year; })
      .filter(function (y, i, all) { return all.indexOf(y) === i; })
      .sort(function (a, b) { return b - a; });

    filters.innerHTML = '<div class="pf-bar">' +
      '<input class="pf-q" type="search" placeholder="Search titles, authors, venues" aria-label="Search publications">' +
      '<select class="pf-sel" data-k="f" aria-label="Faculty"><option value="-1">All faculty</option>' +
        order.map(function (i) { return '<option value="' + i + '">' + esc(names[i]) + "</option>"; }).join("") +
      "</select>" +
      '<select class="pf-sel" data-k="y" aria-label="Year"><option value="">All years</option>' +
        years.map(function (y) { return '<option value="' + y + '">' + y + "</option>"; }).join("") +
      "</select>" +
    "</div>";

    var q = filters.querySelector(".pf-q");
    var selF = filters.querySelector('[data-k="f"]'), selY = filters.querySelector('[data-k="y"]');
    var timer = null;
    q.addEventListener("input", function () {
      clearTimeout(timer);
      timer = setTimeout(function () { state.q = q.value.trim().toLowerCase(); draw(); }, 120);
    });
    selF.addEventListener("change", function () {
      state.f = +selF.value;
      draw();
      try { history.replaceState(null, "", state.f >= 0 ? "#" + slug(names[state.f]) : location.pathname); } catch (e) {}
    });
    selY.addEventListener("change", function () { state.y = selY.value; draw(); });

    function matches(p) {
      if (state.f >= 0 && p.faculty.indexOf(state.f) < 0) return false;
      if (state.y && String(p.year) !== state.y) return false;
      if (state.q) {
        var hay = (p.title + " " + p.authors + " " + p.venue).toLowerCase().replace(/\*/g, "");
        if (hay.indexOf(state.q) < 0) return false;
      }
      return true;
    }

    function draw() {
      var list = P.filter(matches);
      if (!list.length) {
        body.innerHTML = '<section class="section"><div class="body"><p>Nothing matches.</p></div></section>';
        return;
      }
      var groups = [], cur = null;
      list.forEach(function (p) {
        var key = p.year >= 2000 ? String(p.year) : (Math.floor(p.year / 10) * 10) + "s";
        if (!cur || cur.key !== key) groups.push(cur = { key: key, items: [] });
        cur.items.push(p);
      });
      body.innerHTML = groups.map(function (g) {
        return '<section class="section"><h2>' + esc(g.key) + "</h2>" +
          '<div class="body"><ul class="list compact">' + g.items.map(paperLi).join("") + "</ul></div></section>";
      }).join("");
    }

    var hash = (location.hash || "").slice(1);
    if (hash) names.forEach(function (n, i) { if (slug(n) === hash) { state.f = i; selF.value = String(i); } });
    draw();
  }

  window.RESEARCH = { renderNetwork: renderNetwork, renderPapers: renderPapers };
